export const icon = (name, size = 16) =>
  `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths[name]}</svg>`;

// The "send to the big chat" button reads "Add to reply" while the chat panel is open and
// "Continue in big chat" while it is collapsed; CSS shows the right one (body.side-collapsed).
export const bigChatLabel = (size = 14, short = false) =>
  `<span class="when-open">${icon('reply', size)}<span class="lbl">Add to reply</span></span>` +
  `<span class="when-collapsed">${icon('chat', size)}<span class="lbl">${short ? 'Big chat' : 'Continue in big chat'}</span></span>`;

// Static markup in index.html uses <i data-icon="name"></i> placeholders.
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach(el => { el.outerHTML = icon(el.dataset.icon, Number(el.dataset.size) || 16); });
}
